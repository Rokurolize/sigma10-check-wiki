#!/usr/bin/env python3
"""Regenerate patterns/INDEX.md from the KB file headers plus SWEEP-RESULTS.tsv.

Ownership model follows build_start.py: INDEX.md is a generated file.
Edit the KB headers or SWEEP-RESULTS.tsv, then run this script; never
hand-edit INDEX.md. `--check` exits non-zero if INDEX.md differs from
the generated form.
"""
import csv
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent

HEADER_PROSE = """# INDEX — pattern knowledge base

Every pattern the Sigma-10 reviews have confirmed, as a mechanism with
an executable static detection recipe. Read SWEEP-PROTOCOL.md before
running a sweep. SUPPLEMENT-TYPES.md is the reference catalogue of JP
localization supplement types (A13) behind KB-11, KB-16, KB-63 and
KB-64. NEGATIVE-LEDGER.md records unfiled observations and recipe
misses. This file is GENERATED by build_index.py from the KB file
headers plus SWEEP-RESULTS.tsv; do not hand-edit it.

**Detection-cost derivation rule.** Each pattern's cost class is
derived from its own recipe: **pure grep** when a single-file grep or
selector scan of the candidate decides the cell; **cross-file diff**
when the recipe needs the candidate compared against another text (its
branch original, its resolved base, the production counterpart, or the
shared sample source); **needs live probe** when static evidence
cannot decide the cell, i.e. the recipe's deciding step is a HEAD or
fullname probe, a live follow-up diff, a wiki-state read, or a render
confirmation (all TRIAGE patterns land here, as do file-provable
patterns whose proof is a probe, e.g. KB-02 and KB-05). Sweeps run
cheapest first (see SWEEP-PROTOCOL.md).

**Last sweep columns.** Hits and undecidable are from
SWEEP-RESULTS.tsv (first sweep, 2026-11-17). For TRIAGE patterns the
hits column is a risk count, not a verdict count. A pattern never
swept would show `never`; every current pattern was swept on
2026-11-17.
"""


def parse_header(path):
    text = path.read_text(encoding="utf-8")
    title = None
    fields = {}
    for line in text.splitlines():
        if title is None and line.startswith("# "):
            m = re.match(r"#\s+(KB-\d+)\s+—\s+(.*)$", line)
            if m:
                title = m.group(2).strip()
                continue
        m = re.match(r"- \*\*(Class|Detection cost|Provability|Status|Support):\*\*\s*(.*)$", line)
        if m:
            fields[m.group(1)] = m.group(2).strip()
    return title, fields


def load_results():
    results = {}
    with (HERE / "SWEEP-RESULTS.tsv").open(encoding="utf-8") as fh:
        for row in csv.DictReader(fh, delimiter="\t"):
            results[row["id"]] = row
    return results


def generate():
    results = load_results()
    files = sorted(HERE.glob("KB-*.md"))
    rows = []
    total_hits = 0
    total_undec = 0
    for path in files:
        pid = path.stem
        title, fields = parse_header(path)
        res = results.get(pid)
        if res is None:
            sweep = "never"
        else:
            sweep = f"{res['hits']}/{res['undecidable']}"
            total_hits += int(res["hits"])
            total_undec += int(res["undecidable"])
        rows.append(
            "| {id} | [{f}]({f}) | {title} | {cls} | {cost} | {prov} | {status} | {support} | {sweep} |".format(
                id=pid, f=path.name, title=title or "",
                cls=fields.get("Class", ""), cost=fields.get("Detection cost", ""),
                prov=fields.get("Provability", ""), status=fields.get("Status", ""),
                support=fields.get("Support", ""), sweep=sweep))
    out = [HEADER_PROSE]
    out.append("| ID | File | Title | Class | Detection cost | Provability | Status | Support | Last sweep hits/undecidable |")
    out.append("|---|---|---|---|---|---|---|---|---|")
    out.append("")
    out.extend(rows)
    out.append("")
    out.append("## Totals")
    out.append("")
    out.append(f"- Patterns: {len(files)} (KB-01 to KB-{len(files):02d}), plus SWEEP-PROTOCOL.md, SUPPLEMENT-TYPES.md and NEGATIVE-LEDGER.md.")
    out.append(f"- Total confirmed hits (SWEEP-RESULTS.tsv, first sweep 2026-11-17): {total_hits}. For TRIAGE patterns this is a risk count, not a verdict count; units follow each source report (themes for most patterns, occurrences, rows or report mentions where the report counts those).")
    out.append(f"- Total undecidable cells (SWEEP-RESULTS.tsv): {total_undec}. This sum includes the whole-population by-design undecidable patterns KB-19 and KB-48 (287 each) and the probe queues KB-02 (80) and KB-05 (251).")
    out.append("")
    return "\n".join(out)


def main():
    generated = generate()
    index = HERE / "INDEX.md"
    if "--check" in sys.argv[1:]:
        if index.read_text(encoding="utf-8") != generated:
            print("INDEX.md differs from the generated form; run build_index.py", file=sys.stderr)
            return 1
        print("INDEX.md is up to date")
        return 0
    index.write_text(generated, encoding="utf-8")
    print("INDEX.md regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
